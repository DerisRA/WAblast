_patterns = [(re.compile(pattern, re.DOTALL), replacement) for pattern, replacement in PATTERNS]


def tr(text):
    """Translate application-owned display text, leaving unknown text untouched."""
    if not isinstance(text, str):
        return text
    if _language == 'id':
        match = re.fullmatch(r'Gateway request failed \(HTTP (\d+)\)\. Check the server and endpoint configuration\.', text)
        if match:
            return 'Permintaan gateway gagal (HTTP {}). Periksa konfigurasi server dan endpoint.'.format(*match.groups())
        match = re.fullmatch(r'Manual delay: (\d+) seconds; batch rest: (\d+) seconds\.', text)
        if match:
            return 'Jeda manual: {} detik; istirahat batch: {} detik.'.format(*match.groups())
        return ENGLISH_UI.get(text, text)
    if text in CATALOG:
        return CATALOG[text]
    note = '\n\nCatatan: Nomor salah, duplikat, atau opt-out otomatis dilewati.'
    if text.endswith(note):
        return tr(text[:-len(note)]) + CATALOG[note]
    image_error = re.fullmatch(r'(.*?): (.*?)\nPilih gambar yang valid pada menu Template\.', text, re.DOTALL)
    if image_error:
        name, error = image_error.groups()
        return '{}: {}\nChoose a valid image in Templates.'.format(name, tr(error))
    countdown = re.fullmatch(r'(Istirahat batch \(\d+ selesai\)|Jeda manual|Jeda acak) \((\d+:\d+)\) - (Pesan siap|Menyiapkan pesan) ke (.*)', text)
    if countdown:
        prefix, remaining, detail, phone = countdown.groups()
        return '{} ({}) - {} to {}'.format(tr(prefix), remaining, tr(detail), phone)
    for pattern, replacement in _patterns:
        match = pattern.fullmatch(text)
        if match:
            groups = list(match.groups())
            if text.startswith('Selesai ') and len(groups) == 4:
                groups[-1] = CATALOG.get(groups[-1], groups[-1])
            return replacement.format(*groups)
    return text


